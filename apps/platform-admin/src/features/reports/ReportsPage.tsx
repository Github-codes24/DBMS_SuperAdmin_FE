function VendorDonut() {
  const total = vendorStatusData.reduce((sum, item) => sum + item.value, 0)
  return (
    <div className="reports-vendor-chart">
      <svg viewBox="0 0 120 120" role="img" aria-label={`Vendor status distribution for ${total} vendors`}>
        <title>Vendor status distribution</title>
        <circle className="reports-donut-track" cx="60" cy="60" r="44" />
        {vendorStatusData.map((item, index) => {
          const segmentLength = (item.value / total) * donutCircumference
          const currentOffset = vendorStatusData
            .slice(0, index)
            .reduce((sum, segment) => sum + (segment.value / total) * donutCircumference, 0)
          return (
            <circle
              className="reports-donut-segment"
              key={item.label}
              cx="60"
              cy="60"
              r="44"
              stroke={item.color}
              strokeDasharray={`${segmentLength} ${donutCircumference - segmentLength}`}
              strokeDashoffset={-currentOffset}
              strokeLinecap="round"
            >
              <title>{item.label}: {item.value} ({Math.round((item.value / total) * 100)}%)</title>
            </circle>
          )
        })}
        <text className="reports-donut-total" x="60" y="58">{total}</text>
        <text className="reports-donut-caption" x="60" y="73">Total vendors</text>
      </svg>
      <div className="reports-vendor-legend">
        {vendorStatusData.map((item) => (
          <div className="reports-vendor-legend-item" key={item.label}>
            <span><i style={{ backgroundColor: item.color }} />{item.label}</span>
            <strong>{item.value}<small>{Math.round((item.value / total) * 100)}%</small></strong>
          </div>
        ))}
      </div>
    </div>
  )
}

